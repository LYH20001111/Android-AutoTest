package com.newland.nsdk.core.api.common.led;

/**
 * LED light color.
 */
public enum LEDColor {
    /**
     * Blue light.
     */
    BLUE,

    /**
     * Green light.
     */
    GREEN,

    /**
     * Yellow light.
     */
    YELLOW,

    /**
     * Red light.
     */
    RED,

    /**
     * First light.(Only external device supported.)
     */
    FIRST,

    /**
     * Second light.(Only external device supported.)
     */
    SECOND,

    /**
     * Third light.(Only external device supported.)
     */
    THIRD,

    /**
     * Forth light.(Only external device supported.)
     */
    FORTH
}
