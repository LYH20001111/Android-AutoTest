package com.newland.nsdk.core.api.common.serialport;

/**
 * The number of data bits in each character.
 */
public enum DataBits {
    /**
     * 5 data bits
     */
    DATA_BIT_5,

    /**
     * 6 data bits
     */
    DATA_BIT_6,

    /**
     * 7 data bits
     */
    DATA_BIT_7,

    /**
     * 8 data bits
     */
    DATA_BIT_8
}
